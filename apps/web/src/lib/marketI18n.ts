export type MarketTextKey = keyof (typeof dictionaries)["en"];

function primaryLocale() {
  return String(locale.value).toLowerCase();
}

export function marketText(key: MarketTextKey, values?: readonly string[]) {
  const code = primaryLocale();
  const dictionary = code.startsWith("vi") ? dictionaries.vi
    : code.startsWith("zh-tw") || code.startsWith("zh-hant") ? dictionaries.zhTw
      : code.startsWith("zh") ? dictionaries.zhCn
        : dictionaries.en;
  const template = dictionary[key] ?? dictionaries.en[key];
  return values?.length ? template.replace(/\{(\d+)\}/g, (match, index) => values[Number(index)] ?? match) : template;
}

export function formatPrice(value: number) {
  return new Intl.NumberFormat(primaryLocale()).format(value);
}

export function formatMoney(value: number) {
  const symbol = primaryLocale().startsWith("vi") ? "đ" : "₫";
  return `${formatPrice(value)}${symbol}`;
}
